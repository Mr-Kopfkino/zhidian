"""Remove reviewed build-only files from the bundled Windows inference runtime.

Dry-run is the default. Use --apply only after the bundled engine passes a real
inference smoke test. Runtime DLLs, Python modules, dictionaries, package metadata
other than pip/wheel, and third-party licenses are retained.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import stat

SITE = "runtime/Lib/site-packages"
# Reviewed for the bundled torch 2.6.0+cu124 wheel. These .lib files are linker
# inputs, not DLLs loaded by the Windows loader. Keep all .dll/.pyd unchanged.
# Laidian uses precompiled operators/TorchScript, with BigVGAN CUDA extensions
# disabled; this distribution does not compile C++ extensions or use Inductor.
LINK_LIBRARIES = (
    "_C.lib", "asmjit.lib", "c10.lib", "c10_cuda.lib", "caffe2_nvrtc.lib",
    "cpuinfo.lib", "dnnl.lib", "fbgemm.lib", "fmt.lib", "kineto.lib",
    "libprotobuf-lite.lib", "libprotobuf.lib", "libprotoc.lib",
    "microkernels-prod.lib", "pthreadpool.lib", "shm.lib", "sleef.lib",
    "torch.lib", "torch_cpu.lib", "torch_cuda.lib", "torch_python.lib", "XNNPACK.lib",
)
BUILD_DIRECTORIES = {
    f"{SITE}/torch/include": "torch_headers",
    "runtime/Scripts": "command_launchers",
    f"{SITE}/pip": "pip",
    f"{SITE}/pip-26.3.dist-info": "pip",
    f"{SITE}/wheel": "wheel",
    f"{SITE}/wheel-0.48.0.dist-info": "wheel",
}
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "copyright", "licensing")


def is_reparse(path: Path) -> bool:
    info = path.lstat()
    return stat.S_ISLNK(info.st_mode) or bool(getattr(info, "st_file_attributes", 0)
                                           & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400))


def checked_path(root: Path, relative: str) -> Path:
    parts = Path(relative).parts
    if Path(relative).is_absolute() or any(part in {"..", "."} for part in parts):
        raise ValueError(f"Unsafe relative path: {relative}")
    target = root
    for part in parts:
        target = target / part
        if os.path.lexists(target) and is_reparse(target):
            raise ValueError(f"Refusing linked/reparse path: {relative}")
    if not target.resolve().is_relative_to(root):
        raise ValueError(f"Path escapes engine root: {relative}")
    return target


def licensed_path(path: Path, root: Path) -> bool:
    return any(part.casefold().startswith(LICENSE_PREFIXES) for part in path.relative_to(root).parts)


def walk_checked(root: Path, directory: Path):
    for current, children, files in os.walk(directory, followlinks=False):
        current = Path(current)
        for name in children + files:
            checked_path(root, (current / name).relative_to(root).as_posix())
        yield current, [current / name for name in files]


def rebuildable_cache(path: Path) -> bool:
    # Never remove source-less bytecode. Only ordinary CPython/Numba caches with
    # an adjacent source module can be regenerated by this distribution.
    if path.parent.name != "__pycache__" or path.suffix.casefold() not in {".pyc", ".pyo", ".nbi", ".nbc"}:
        return False
    return (path.parent.parent / (path.name.split(".", 1)[0] + ".py")).is_file()


def trim(engine_root: Path, apply: bool = False) -> dict:
    supplied = engine_root.absolute()
    root = supplied.resolve(strict=True)
    if not root.is_dir() or is_reparse(supplied) or supplied != root:
        raise ValueError("Engine root must be a real directory, not a link/junction")
    runtime = checked_path(root, "runtime")
    if not runtime.is_dir():
        raise ValueError("Bundled runtime directory is missing")
    candidates, directories = {}, set()

    def add(path: Path, group: str):
        if not licensed_path(path, root):
            info = path.stat()
            candidates[path] = (group, info.st_size, info.st_mtime_ns)

    for name in LINK_LIBRARIES:
        path = checked_path(root, f"{SITE}/torch/lib/{name}")
        if path.exists():
            if not path.is_file():
                raise ValueError(f"Expected linker file: {path.name}")
            add(path, "torch_link_libraries")
    for relative, group in BUILD_DIRECTORIES.items():
        directory = checked_path(root, relative)
        if not directory.exists():
            continue
        if not directory.is_dir():
            raise ValueError(f"Expected build directory: {relative}")
        for current, files in walk_checked(root, directory):
            directories.add(current)
            for path in files:
                add(path, group)
    # Cache discovery is bounded to the packaged runtime, not user/global caches.
    # There is no generic deletion of tests, testing, headers or development
    # packages: torch.testing and setuptools are used by inference imports.
    for current, files in walk_checked(root, runtime):
        if current.name == "__pycache__":
            directories.add(current)
            for path in files:
                if path not in candidates and rebuildable_cache(path):
                    add(path, "rebuildable_cache")
    files, groups = [], {}
    for path, (group, length, _) in sorted(candidates.items()):
        files.append({"path": path.relative_to(root).as_posix(), "bytes": length, "group": group})
        summary = groups.setdefault(group, {"files": 0, "bytes": 0})
        summary["files"] += 1
        summary["bytes"] += length
    report = {"dry_run": not apply, "file_count": len(files), "bytes": sum(f["bytes"] for f in files),
              "groups": groups, "files": files, "removed_empty_directories": []}
    if not apply:
        return report
    # Recheck every target before the first unlink. Packaging must not race a
    # package installation or inference worker writing these same paths.
    for path, (_, length, modified) in candidates.items():
        checked_path(root, path.relative_to(root).as_posix())
        info = path.stat()
        if not path.is_file() or info.st_size != length or info.st_mtime_ns != modified:
            raise ValueError(f"Runtime changed during preflight: {path.relative_to(root)}")
    for path in candidates:
        path.unlink()
    for directory in sorted(directories, key=lambda p: len(p.parts), reverse=True):
        if not licensed_path(directory, root) and not any(directory.iterdir()):
            directory.rmdir()
            report["removed_empty_directories"].append(directory.relative_to(root).as_posix())
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine-root", required=True, type=Path)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--apply", action="store_true")
    mode.add_argument("--dry-run", action="store_true")
    parser.add_argument("--report", type=Path, help="Write the complete path-by-path JSON plan/report")
    args = parser.parse_args()
    try:
        result = trim(args.engine_root, apply=args.apply)
        if args.report:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(json.dumps({k: v for k, v in result.items() if k != "files"}, ensure_ascii=False, indent=2))
    except (OSError, ValueError) as error:
        parser.exit(1, f"Runtime trim aborted: {error}\n")


if __name__ == "__main__":
    main()
